import PageContainer from "@/components/layout/page-container";
import { callMethod } from "@/lib/call-method";
import NodraDocTypes from "@/features/nodra/docktypes";
import { createFileRoute } from "@tanstack/react-router";

export const Route = createFileRoute("/dashboard/nodra/doctypes")({
  loader: async () => {
    const result = await callMethod("nodra.doctypes");

    return (result as any).doctypes;
  },
  component: RouteComponent,
});

function RouteComponent() {
  const doctypes = Route.useLoaderData();

  return (
    <PageContainer
      pageTitle="Nodra DocTypes"
      pageDescription="List of doctypes generated by Nodra"
    >
      <NodraDocTypes doctypes={doctypes} />
    </PageContainer>
  );
}
