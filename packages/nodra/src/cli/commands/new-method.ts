/**
 * `new:method <Doctype>` — app-scoped.
 *
 * Scaffolds src/server/methods/<slug>.ts with CRUD methods registered
 * through Nodra's method registry, not TanStack Start server functions.
 *
 * The generated module exports a registration function so the app's
 * existing method bootstrap can register it explicitly.
 */
import type { Command } from "commander";
import { mkdir, writeFile, access } from "node:fs/promises";
import path from "node:path";

function toPascalCase(input: string): string {
  return input
    .trim()
    .split(/[\s_-]+/)
    .filter(Boolean)
    .map((word) => word.charAt(0).toUpperCase() + word.slice(1))
    .join("");
}

function toSlug(input: string): string {
  return input
    .trim()
    .replace(/([a-z0-9])([A-Z])/g, "$1-$2")
    .replace(/[\s_]+/g, "-")
    .toLowerCase();
}

async function pathExists(filePath: string): Promise<boolean> {
  try {
    await access(filePath);
    return true;
  } catch {
    return false;
  }
}

function buildMethodTs(
  doctypeName: string,
  className: string,
  slug: string,
): string {
  return `/**
 * Nodra methods for the "${doctypeName}" doctype.
 *
 * Generated by \`new:method ${doctypeName}\`.
 *
 * Register this module from the app's method bootstrap.
 */
import type { MethodRegistry } from "nodra";
import { Filters, ListOptions } from "nodra/orm/crud";
import { ${className} } from "../../../doctypes/${slug}/${slug}";
import { getNodra } from "../nodra-app";
import { serialise } from "../http";

type RecordData = Record<string, unknown>;

function isRecord(value: unknown): value is RecordData {
  return (
    value !== null &&
    typeof value === "object" &&
    !Array.isArray(value)
  );
}

function getRequiredName(value: unknown): string {
  const name = String(value ?? "").trim();

  if (!name) {
    throw new Error("${doctypeName} name is required");
  }

  return name;
}

export function register${className}Methods(
  registry: MethodRegistry,
): void {
  registry.register(
    "${slug}.get",
    async (ctx) => {
      const name = getRequiredName(ctx.args.name);
      const app = await getNodra();

      const doc = await app.orm.getDoc("${doctypeName}", name);

      return serialise(doc);
    },
    { requireAuth: true },
  );

  registry.register(
    "${slug}.list",
    async (ctx) => {
      const app = await getNodra();
      const args = ctx.args;

      const requestedLimit = Number(args.limit);
      const requestedOffset = Number(args.offset);

      const limit = Number.isFinite(requestedLimit)
        ? Math.min(100, Math.max(1, Math.trunc(requestedLimit)))
        : 20;

      const offset = Number.isFinite(requestedOffset)
        ? Math.max(0, Math.trunc(requestedOffset))
        : 0;

      const fields = Array.isArray(args.fields)
        ? args.fields.filter(
            (field): field is string =>
              typeof field === "string",
          )
        : undefined;

      let filters: Filters | undefined;

      if (args.filters !== undefined) {
        if (!isRecord(args.filters)) {
          throw new Error("${doctypeName} filters must be an object");
        }

        // The cast bridges the generic request payload and Nodra's
        // Filters type. Validate supported filter operators and fields
        // before passing client-provided filters to the ORM.
        filters = args.filters as Filters;
      }

      const options: ListOptions = {
        limit,
        offset,
        ...(fields ? { fields } : {}),
        ...(filters ? { filters } : {}),
        ...(typeof args.orderBy === "string"
          ? { orderBy: args.orderBy }
          : {}),
      };

      const [docs, totalCount] = await Promise.all([
        app.orm.getList("${doctypeName}", options),
        app.orm.getCount("${doctypeName}", filters),
      ]);

      return {
        data: docs.map((doc) => serialise(doc)),
        meta: {
          total_count: totalCount,
          limit,
          offset,
        },
      };
    },
    { requireAuth: true },
  );

  registry.register(
    "${slug}.create",
    async (ctx) => {
      const data: unknown = ctx.args.data;

      if (!isRecord(data)) {
        throw new Error("${doctypeName} data must be an object");
      }

      const app = await getNodra();
      const meta = app.registry.get("${doctypeName}");
      const doc = new ${className}(
        meta,
        data,
      );

      const inserted = await app.orm.insert(doc);

      return serialise(inserted);
    },
    { requireAuth: true },
  );

  registry.register(
    "${slug}.update",
    async (ctx) => {
      const name = getRequiredName(ctx.args.name);
      const data: unknown = ctx.args.data;

      if (!isRecord(data)) {
        throw new Error("${doctypeName} data must be an object");
      }

      const app = await getNodra();
      const meta = app.registry.get("${doctypeName}");

      // Load the current document using the ORM.
      const existing = await app.orm.getDoc("${doctypeName}", name);

      // Do not assume the Document has a data property.
      // Read existing values using the Document API supported by Nodra.
      const doc = new ${className}(meta, { name });

      for (const [key, value] of Object.entries(data)) {
        doc.set(key, value);
      }

      const updated = await app.orm.update(doc);

      return serialise(updated);
    },
    { requireAuth: true },
  );

  registry.register(
    "${slug}.delete",
    async (ctx) => {
      const name = getRequiredName(ctx.args.name);
      const app = await getNodra();

      await app.orm.deleteDoc("${doctypeName}", name);

      return { message: "ok" as const };
    },
    { requireAuth: true },
  );
}
`;
}

export function registerNewMethodCommand(program: Command): void {
  program
    .command("new:method <doctype>")
    .description(
      "Scaffold Nodra CRUD methods for a doctype " +
        "(requires a matching doctype created via new:doctype)",
    )
    .action(async (rawName: string) => {
      const className = toPascalCase(rawName);
      const doctypeName = className;
      const slug = toSlug(rawName);

      if (!className || !slug) {
        console.error("Error: Doctype name cannot be empty.");
        process.exitCode = 1;
        return;
      }

      const appRoot = process.cwd();

      // Doctypes live at the app root, not inside src/.
      const doctypeFile = path.join(appRoot, "doctypes", slug, `${slug}.ts`);

      if (!(await pathExists(doctypeFile))) {
        console.error(
          `Error: doctypes/${slug}/${slug}.ts not found.\n` +
            `Run "new:doctype ${doctypeName}" first.`,
        );
        process.exitCode = 1;
        return;
      }

      const outDir = path.join(appRoot, "src", "server", "methods");
      const outPath = path.join(outDir, `${slug}.ts`);

      if (await pathExists(outPath)) {
        console.error(
          `Error: src/server/methods/${slug}.ts already exists. Aborting.`,
        );
        process.exitCode = 1;
        return;
      }

      await mkdir(outDir, { recursive: true });

      await writeFile(
        outPath,
        buildMethodTs(doctypeName, className, slug),
        "utf-8",
      );

      console.log(`Created src/server/methods/${slug}.ts`);
      console.log(
        `  ${slug}.get, ${slug}.list, ${slug}.create, ` +
          `${slug}.update, ${slug}.delete`,
      );
      console.log(`  Export: register${className}Methods(registry)`);
      console.log(
        "  Next: register the generated module in your method bootstrap.",
      );
    });
}
